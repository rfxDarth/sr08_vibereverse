/* Convert a quotient/remainder sequence to the ring's display digits. */
#include "firmware/reconstructed/include/sr08_display_value_formatters.h"

__attribute__((used, naked, section(".text.convert_quotient_remainder_sequence_ring_s_at_3148"))) void
convert_quotient_remainder_sequence_ring_s_at_3148(uint32_t value, volatile uint8_t *output, uint32_t digit_count,
                                                   uint32_t display_mode) {
    __asm__ volatile("push {r4, r5, r6, r7, lr}\n"
                     "sub sp, #36\n"
                     "str r3, [sp, #20]\n"
                     "str r1, [sp, #8]\n"
                     "str r0, [sp, #16]\n"
                     "add r0, sp, #28\n"
                     "adds r0, r2, r0\n"
                     "subs r0, r0, #1 /* subs r0, r0, #1 */\n"
                     "str r0, [sp, #12]\n"
                     "str r2, [sp, #4]\n"
                     "negs r0, r2\n"
                     "str r0, [sp, #24]\n"
                     "movs r6, #1\n"
                     "movs r5, #0\n"
                     "ldr r4, [sp, #16]\n"
                     ".Ldigits_loop: ldr r0, [sp, #24]\n"
                     "cmp r0, r5\n"
                     "beq .Lencode\n"
                     "mov r0, r4\n"
                     "mov r1, r6\n"
                     "bl __aeabi_uidiv\n"
                     "movs r7, #10\n"
                     "mov r1, r7\n"
                     "bl __aeabi_uidiv\n"
                     "cmp r6, r4\n"
                     "bhi .Lbase_digit\n"
                     "mov r2, r1\n"
                     "b .Ldigit_ready\n"
                     ".Lbase_digit: movs r2, #16\n"
                     ".Ldigit_ready: subs r0, r5, #1\n"
                     "cmp r0, r5\n"
                     "mov r3, r1\n"
                     "bcs .Lpadding_check\n"
                     "mov r3, r2\n"
                     ".Lpadding_check: ldr r2, [sp, #20]\n"
                     "cmp r2, #1\n"
                     "beq .Lstore_digit\n"
                     "mov r3, r1\n"
                     ".Lstore_digit: ldr r1, [sp, #12]\n"
                     "strb r3, [r1, r5]\n"
                     "muls r6, r7\n"
                     "mov r5, r0\n"
                     "b .Ldigits_loop\n"
                     ".Lencode: add r0, sp, #28\n"
                     ".set .Ldigit_encoding_table, .+28\n"
                     "adr r1, .Ldigit_encoding_table /* digit encoding table at 0x07fc31c0 */\n"
                     "ldr r3, [sp, #8]\n"
                     "ldr r4, [sp, #4]\n"
                     ".Lencode_loop: cmp r4, #0\n"
                     "beq .Lreturn\n"
                     "ldrb r2, [r0, #0]\n"
                     "ldrb r2, [r1, r2]\n"
                     "strb r2, [r3, #0]\n"
                     "subs r4, r4, #1 /* subs r4, r4, #1 */\n"
                     "adds r3, r3, #1 /* adds r3, r3, #1 */\n"
                     "adds r0, r0, #1 /* adds r0, r0, #1 */\n"
                     "b .Lencode_loop\n"
                     ".Lreturn: add sp, #36\n"
                     "pop {r4, r5, r6, r7, pc}\n");
}
