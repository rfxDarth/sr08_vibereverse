scan_five_masked_records_and_dispatch_entries(void) {
    __asm__ volatile("push {r3, r4, r5, r6, r7, lr}\n"
                     "cmp r1, #7\n"
                     "bhi .Linvalid_record_index\n"
                     "mov r4, r1\n"
                     "ldr r5, [pc, #816]\n"
                     "adds r5, #20\n"
                     "movs r6, #1\n"
                     "ldr r7, [pc, #820]\n"
                     ".Lcheck_next_record: cmp r6, #6\n"
                     "beq .Lscan_complete\n"
                     "movs r0, #42\n"
                     "lsrs r0, r6\n"
                     "lsls r0, r0, #31\n"
                     "beq .Ladvance_record\n"
                     "ldr r0, [r5, #0]\n"
                     "ldrh r0, [r0, #0]\n"
                     "cmp r0, r7\n"
                     "bne .Ladvance_record\n"
                     "uxtb r1, r6\n"
                     "movs r2, #0\n"
                     "mov r0, r4\n"
                     "bl replace_byte_in_variable_length_record_at_index\n"
                     ".Ladvance_record: adds r5, #20\n"
                     "adds r6, r6, #1\n"
                     "b .Lcheck_next_record\n"
                     ".Linvalid_record_index: ldr r0, [pc, #896]\n"
                     "movs r1, #200\n"
                     "strh r1, [r0, #0]\n"
                     "ldr r0, [pc, #896]\n"
                     "movs r1, #8\n"
                     "strh r1, [r0, #0]\n"
                     ".Lhalt_invalid_record_index: b .Lhalt_invalid_record_index\n"
                     ".Lscan_complete: pop {r3, r4, r5, r6, r7, pc}\n");
}
