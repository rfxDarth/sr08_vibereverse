/* Recovered behavior:
 * Format into a 96-byte bounded buffer and send it through the UART. The supported conversions are
 * %c, %s, %d, %i, %u, %x, and %X, with an optional h modifier and one-digit zero-prefixed width.
 * An unsupported conversion emits the firmware's fatal-format diagnostic.
 */
#include <stdint.h>

extern uint32_t format_integer_radix_zero_padded(int32_t value, int32_t radix, uint32_t uppercase_hex, char *buffer,
                                                 uint32_t minimum_width);
extern void append_bounded_bytes_and_terminate(uint8_t **, uint8_t *, const uint8_t *, uint32_t);
extern void transmit_uart_buffer(const uint8_t *, int32_t);

/* Render literals and %c/%s/%d/%i/%u/%x/%X into a 96-byte stack buffer,
 * then transmit it through the UART helper. The parser accepts a one-digit
 * width after %0 and skips an optional h modifier. Unsupported conversions
 * emit "FATAL: unsupported printf character: <char>.\n". Keep the Thumb body
 * explicit because it implements V204's register/stack variadic ABI exactly.
 */
__attribute__((used, naked, section(".text.format_and_send_uart_message"))) uint32_t
format_and_send_uart_message(const uint8_t *format, ...) {
    __asm__ volatile("sub sp, #12\n"
                     "push {r4, r5, r6, r7, lr}\n"
                     "sub sp, #136\n"
                     "mov r6, r0\n"
                     "add r0, sp, #156\n"
                     "stmia r0!, {r1, r2, r3}\n"
                     "add r4, sp, #156\n"
                     "str r4, [sp, #104]\n"
                     "add r1, sp, #8\n"
                     "str r1, [sp, #132]\n"
                     "movs r0, #1\n"
                     "subs r5, r0, r1\n"
                     "L_loop: ldrb r0, [r6, #0]\n"
                     "L_loop_check:"
                     "adds r2, r5, r1\n"
                     "cmp r2, #95\n"
                     "bhi L_done\n"
                     "cmp r0, #37\n"
                     "bne L_char\n"
                     "ldrb r7, [r6, #1]\n"
                     "adds r0, r6, #2\n"
                     "cmp r7, #48\n"
                     "bne L_no_width\n"
                     "ldrb r2, [r0, #0]\n"
                     "cmp r2, #0\n"
                     "beq L_done\n"
                     "subs r2, #48\n"
                     "uxtb r0, r2\n"
                     "cmp r0, #10\n"
                     "bcc L_width_digit\n"
                     "movs r2, #0\n"
                     "L_width_digit: ldrb r7, [r6, #3]\n"
                     "adds r0, r6, #4\n"
                     "b L_length\n"
                     "L_char: adds r6, r6, #1\n"
                     "L_store_char:"
                     "strb r0, [r1, #0]\n"
                     "movs r0, #0\n"
                     "strb r0, [r1, #1]\n"
                     "adds r0, r1, #1\n"
                     "str r0, [sp, #132]\n"
                     "b L_next\n"
                     "L_no_width: movs r2, #0\n"
                     "L_length: movs r3, #4\n"
                     "orrs r3, r7\n"
                     "cmp r3, #108\n"
                     "bne L_specifier\n"
                     "ldrb r7, [r0, #0]\n"
                     "adds r6, r0, #1\n"
                     "b L_dispatch\n"
                     "L_specifier: mov r6, r0\n"
                     "L_dispatch: cmp r7, #88\n"
                     "beq L_integer\n"
                     "cmp r7, #99\n"
                     "beq L_char_arg\n"
                     "cmp r7, #100\n"
                     "beq L_decimal\n"
                     "cmp r7, #105\n"
                     "beq L_decimal\n"
                     "cmp r7, #115\n"
                     "beq L_string\n"
                     "cmp r7, #117\n"
                     "beq L_integer\n"
                     "cmp r7, #120\n"
                     "beq L_integer\n"
                     "cmp r7, #0\n"
                     "beq L_done\n"
                     "add r0, sp, #132\n"
                     "add r1, sp, #8\n"
                     "movs r3, #37\n"
                     ".set .Lpercent_format, .+164\n"
                     "adr r2, .Lpercent_format /* format string at 0x07fc5458 */\n"
                     "bl append_bounded_bytes_and_terminate\n"
                     "ldr r0, [sp, #132]\n"
                     "adds r1, r5, r0\n"
                     "cmp r1, #95\n"
                     "bhi L_unknown_append\n"
                     "strb r7, [r0, #0]\n"
                     "movs r1, #0\n"
                     "strb r1, [r0, #1]\n"
                     "adds r0, r0, #1\n"
                     "str r0, [sp, #132]\n"
                     "L_unknown_append: add r0, sp, #132\n"
                     "add r1, sp, #8\n"
                     "movs r3, #2\n"
                     ".set .Lunknown_format, .+174\n"
                     "adr r2, .Lunknown_format /* format string at 0x07fc5480 */\n"
                     "b L_append\n"
                     "L_integer: ldmia r4!, {r0}\n"
                     "uxtb r1, r2\n"
                     "cmp r7, #117\n"
                     "bne L_hex\n"
                     "str r1, [sp, #0]\n"
                     "movs r1, #10\n"
                     "movs r2, #0\n"
                     "b L_add_and_call\n"
                     "L_decimal: ldmia r4!, {r0}\n"
                     "uxtb r1, r2\n"
                     "str r1, [sp, #0]\n"
                     "movs r1, #10\n"
                     "movs r2, #0\n"
                     "add r7, sp, #108\n"
                     "mov r3, r7\n"
                     "bl format_integer_radix_zero_padded\n"
                     "mov r3, r0\n"
                     "add r0, sp, #132\n"
                     "add r1, sp, #8\n"
                     "mov r2, r7\n"
                     "b L_append\n"
                     "L_hex: str r1, [sp, #0]\n"
                     "subs r7, #88\n"
                     "negs r2, r7\n"
                     "adcs r2, r7\n"
                     "movs r1, #16\n"
                     "L_add_and_call:"
                     "add r3, sp, #108\n"
                     "bl format_integer_radix_zero_padded\n"
                     "mov r3, r0\n"
                     "add r0, sp, #132\n"
                     "add r1, sp, #8\n"
                     "add r2, sp, #108\n"
                     "L_append: bl append_bounded_bytes_and_terminate\n"
                     "L_next: ldrb r0, [r6, #0]\n"
                     "ldr r1, [sp, #132]\n"
                     "cmp r0, #0\n"
                     "bne L_loop_check\n"
                     "b L_done\n"
                     "L_char_arg: ldmia r4!, {r0}\n"
                     "b L_store_char\n"
                     "L_string: ldr r2, [r4, #0]\n"
                     "movs r0, #0\n"
                     "L_strlen: ldrb r1, [r2, r0]\n"
                     "adds r0, r0, #1\n"
                     "cmp r1, #0\n"
                     "bne L_strlen\n"
                     "subs r3, r0, #1\n"
                     "add r0, sp, #132\n"
                     "add r1, sp, #8\n"
                     "bl append_bounded_bytes_and_terminate\n"
                     "adds r4, r4, #4\n"
                     "b L_next\n"
                     "L_done: add r0, sp, #8\n"
                     "subs r1, r1, r0\n"
                     "bl transmit_uart_buffer\n"
                     "add sp, #136\n"
                     "pop {r4, r5, r6, r7}\n"
                     "pop {r0}\n"
                     "add sp, #12\n"
                     "bx r0\n");
}
