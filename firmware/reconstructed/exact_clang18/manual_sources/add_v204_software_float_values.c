/* Recovered behavior:
 * Order operands by magnitude, align the smaller significand, combine significands according to
 * the operand signs, then normalize and round the result.
 */
#include <stdint.h>
#include "firmware/reconstructed/include/sr08_software_float.h"

/* Order operands by magnitude, align significands, combine by sign, then
 * normalize and round the software-float result. */
__attribute__((used, naked, section(".text.add_v204_software_float_values"))) uint32_t
add_v204_software_float_values(uint32_t a, uint32_t b, uint32_t unused, int32_t rounding) {
    __asm__ volatile("push {r3, r4, r5, r6, r7, lr}\n"
                     "mov r2, r0\n"
                     "eors r2, r1\n"
                     "lsrs r4, r2, #31\n"
                     "lsls r2, r0, #1\n"
                     "lsls r3, r1, #1\n"
                     "lsrs r2, r2, #1\n"
                     "lsrs r3, r3, #1\n"
                     "cmp r2, r3\n"
                     "bcs .Loperands_ordered\n"
                     "mov r2, r0\n"
                     "mov r0, r1\n"
                     "mov r1, r2\n"
                     ".Loperands_ordered: lsls r2, r1, #1\n"
                     "beq .Lreturn\n"
                     "lsrs r3, r0, #23\n"
                     "lsls r2, r1, #1\n"
                     "uxtb r5, r3\n"
                     "lsrs r2, r2, #24\n"
                     "subs r5, r5, r2\n"
                     "cmp r5, #32\n"
                     "bge .Llarge_exponent_gap\n"
                     "lsls r1, r1, #9\n"
                     "movs r6, #1\n"
                     "lsrs r1, r1, #9\n"
                     "lsls r6, r6, #23\n"
                     "adds r2, r1, r6\n"
                     "cmp r4, #0\n"
                     "beq .Lalign_significand\n"
                     "negs r2, r2\n"
                     ".Lalign_significand: movs r1, #32\n"
                     "subs r7, r1, r5\n"
                     "mov r1, r2\n"
                     "lsls r1, r7\n"
                     "asrs r2, r5\n"
                     "adds r0, r2, r0\n"
                     "lsrs r2, r0, #23\n"
                     "cmp r2, r3\n"
                     "beq .Lround_result\n"
                     "cmp r4, #0\n"
                     "beq .Lnormalize_same_sign\n"
                     "cmp r5, #1\n"
                     "bgt .Llarge_opposite_sign_difference\n"
                     "lsls r2, r3, #23\n"
                     "subs r0, r0, r2\n"
                     "lsrs r2, r2, #31\n"
                     "adds r0, r0, r6\n"
                     "lsls r2, r2, #31\n"
                     "uxtb r3, r3\n"
                     "bl normalize_and_round_v204_software_float\n"
                     ".Lreturn: pop {r3, r4, r5, r6, r7, pc}\n"
                     ".Llarge_opposite_sign_difference: lsls r2, r3, #23\n"
                     "subs r0, r0, r2\n"
                     "movs r3, #1\n"
                     "lsls r0, r0, #1\n"
                     "lsls r3, r3, #24\n"
                     "adds r0, r0, r3\n"
                     "adds r0, r0, r2\n"
                     "negs r2, r3\n"
                     "adds r0, r0, r2\n"
                     "lsrs r2, r1, #31\n"
                     "orrs r0, r2\n"
                     "lsls r1, r1, #1\n"
                     "b .Lround_result\n"
                     ".Lnormalize_same_sign: lsrs r1, r1, #1\n"
                     "lsls r2, r0, #31\n"
                     "orrs r1, r2\n"
                     "lsls r2, r3, #23\n"
                     "subs r0, r0, r2\n"
                     "adds r0, r0, r6\n"
                     "lsrs r0, r0, #1\n"
                     "adds r0, r0, r2\n"
                     ".Lround_result: bl round_v204_float_value_from_status\n"
                     "pop {r3, r4, r5, r6, r7, pc}\n"
                     ".Llarge_exponent_gap: lsls r1, r4, #1\n"
                     "movs r2, #1\n"
                     "subs r1, r2, r1\n"
                     "subs r0, r0, r4\n"
                     "b .Lround_result\n");
}
