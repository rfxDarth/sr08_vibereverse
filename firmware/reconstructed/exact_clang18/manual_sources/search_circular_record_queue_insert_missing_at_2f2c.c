/* Search the circular record queue, insert a missing item, and flush if full. */
#include "firmware/reconstructed/include/sr08_ring_buffer.h"
__attribute__((used, naked, section(".text.search_circular_record_queue_insert_missing_at_2f2c"))) void
search_circular_record_queue_insert_missing_at_2f2c(const void *record, uint32_t record_size_bytes) {
    __asm__ volatile("push {r4, r5, r6, r7, lr}\n"
                     "sub sp, #20\n"
                     "str r1, [sp, #4]\n"
                     "str r0, [sp, #16]\n"
                     "ldr r1, [pc, #80]\n"
                     "ldr r0, [r1, #52]\n"
                     "str r0, [sp, #12]\n"
                     "ldr r4, [r1, #56]\n"
                     "ldr r0, [r1, #60]\n"
                     "ldr r2, [r1, #64]\n"
                     "str r2, [sp, #8]\n"
                     "ldr r7, [r1, #68]\n"
                     "subs r6, r0, #1\n"
                     ".Lscan_queue: ldr r0, [sp, #12]\n"
                     "cmp r4, r0\n"
                     "beq .Lenqueue_new_record\n"
                     "mov r0, r4\n"
                     "ldr r1, [sp, #8]\n"
                     "muls r0, r1\n"
                     "adds r5, r7, r0\n"
                     "mov r0, r5\n"
                     "ldr r1, [sp, #16]\n"
                     "ldr r2, [sp, #4]\n"
                     "bl memcmp\n"
                     "cmp r0, #0\n"
                     "beq .Lreplace_matching_record\n"
                     "adds r4, r4, #1\n"
                     "ands r4, r6\n"
                     "b .Lscan_queue\n"
                     ".Lreplace_matching_record: mov r0, r5\n"
                     "ldr r1, [sp, #16]\n"
                     "ldr r2, [sp, #8]\n"
                     "bl __aeabi_memcpy\n"
                     "ldr r0, [pc, #20]\n"
                     "ldr r0, [r0, #52]\n"
                     "cmp r4, r0\n"
                     "bne .Lreturn\n"
                     ".Lenqueue_new_record: ldr r0, [pc, #12]\n"
                     "adds r0, #52\n"
                     "ldr r1, [sp, #16]\n"
                     "bl enqueue_ring_record_if_space\n"
                     ".Lreturn: add sp, #20\n"
                     "pop {r4, r5, r6, r7, pc}\n");
}
