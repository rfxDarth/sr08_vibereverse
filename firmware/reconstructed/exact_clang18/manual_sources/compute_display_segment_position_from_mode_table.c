#include <stdint.h>

/* Computes the display segment position selected by the SR08 mode table. */
__attribute__((used, naked, section(".text.compute_display_segment_position_from_mode_table"))) uint16_t
compute_display_segment_position_from_mode_table(uint8_t *table, uint32_t row, uint32_t segment, uint32_t column) {
    __asm__ volatile("push {r4, r5, r6, r7, lr}\n"
                     "movs r4, #0\n"
                     "cmp r2, #22\n"
                     "bhi .Lreturn_position\n"
                     "movs r5, #33\n"
                     "ldrb r5, [r0, r5]\n"
                     "cmp r5, r1\n"
                     "bls .Lreturn_position\n"
                     "cmp r2, #19\n"
                     "bcc .Lsum_prior_rows\n"
                     "movs r5, #22\n"
                     "muls r5, r1\n"
                     "adds r5, r0, r5\n"
                     "ldrb r5, [r5, #23]\n"
                     "cmp r5, r3\n"
                     "bls .Lreturn_position\n"
                     ".Lsum_prior_rows: mov r5, r0\n"
                     "adds r5, #22\n"
                     "ldrh r4, [r0, #26]\n"
                     "mov r6, r1\n"
                     ".Lsum_row_loop: cmp r6, #0\n"
                     "beq .Lapply_position_adjustment\n"
                     "ldrb r7, [r5, #0]\n"
                     "adds r4, r4, r7\n"
                     "subs r6, r6, #1\n"
                     "adds r5, #22\n"
                     "b .Lsum_row_loop\n"
                     ".Lapply_position_adjustment: cmp r2, #18\n"
                     "bhi .Lmode_specific_segment\n"
                     "adds r3, r4, r2\n"
                     "movs r4, #22\n"
                     "muls r4, r1\n"
                     "adds r0, r0, r4\n"
                     "ldrh r0, [r0, #4]\n"
                     "lsls r1, r0, #31\n"
                     "bne .Lcheck_position_range\n"
                     "cmp r2, #16\n"
                     "bcc .Lcheck_middle_position\n"
                     "subs r3, r3, #5\n"
                     "b .Lcheck_position_range\n"
                     ".Lmode_specific_segment: movs r5, #22\n"
                     "muls r5, r1\n"
                     "adds r1, r0, r5\n"
                     "ldrb r0, [r1, #24]\n"
                     "adds r0, r4, r0\n"
                     "adds r1, r1, #4\n"
                     "movs r4, #0\n"
                     ".Lcount_enabled_segments: cmp r3, r4\n"
                     "beq .Lcheck_last_segment\n"
                     "ldrh r5, [r1, #0]\n"
                     "lsrs r5, r4\n"
                     "lsls r5, r5, #25\n"
                     "bpl .Lsegment_width_three\n"
                     "movs r5, #4\n"
                     "b .Ladd_segment_width\n"
                     ".Lsegment_width_three: movs r5, #3\n"
                     ".Ladd_segment_width: adds r0, r5, r0\n"
                     "adds r4, r4, #1\n"
                     "b .Lcount_enabled_segments\n"
                     ".Lcheck_last_segment: cmp r2, #22\n"
                     "bne .Lcompute_mode_position\n"
                     "ldrh r1, [r1, #0]\n"
                     "lsrs r1, r3\n"
                     "lsls r1, r1, #25\n"
                     "bmi .Lzero_position\n"
                     ".Lcompute_mode_position: adds r4, r2, r0\n"
                     "subs r4, #19\n"
                     "b .Lreturn_position\n"
                     ".Lcheck_middle_position: cmp r2, #10\n"
                     "bls .Lcheck_position_range\n"
                     "movs r3, #0\n"
                     ".Lcheck_position_range: cmp r2, #15\n"
                     "bhi .Lsign_extend_adjustment\n"
                     "mov r4, r3\n"
                     "b .Lcheck_mode_bit_five\n"
                     ".Lsign_extend_adjustment: lsls r1, r0, #30\n"
                     "asrs r4, r1, #31\n"
                     "ands r4, r3\n"
                     ".Lcheck_mode_bit_five: lsls r1, r0, #29\n"
                     "bmi .Lcheck_mode_bit_four\n"
                     "cmp r2, #11\n"
                     "bcc .Lcheck_mode_bit_three\n"
                     "subs r4, r4, #2\n"
                     "b .Lcheck_mode_bit_four\n"
                     ".Lcheck_mode_bit_three: cmp r2, #8\n"
                     "bls .Lcheck_mode_bit_four\n"
                     "movs r4, #0\n"
                     ".Lcheck_mode_bit_four: lsls r0, r0, #28\n"
                     "bmi .Lreturn_position\n"
                     "cmp r2, #9\n"
                     "bcc .Lcheck_mode_bit_two\n"
                     "subs r4, r4, #2\n"
                     "b .Lreturn_position\n"
                     ".Lcheck_mode_bit_two: cmp r2, #2\n"
                     "bcc .Lcheck_mode_bit_one\n"
                     "subs r4, r4, #1\n"
                     "b .Lreturn_position\n"
                     ".Lcheck_mode_bit_one: cmp r2, #1\n"
                     "bne .Lreturn_position\n"
                     ".Lzero_position: movs r4, #0\n"
                     ".Lreturn_position: uxth r0, r4\n"
                     "pop {r4, r5, r6, r7, pc}\n");
}
