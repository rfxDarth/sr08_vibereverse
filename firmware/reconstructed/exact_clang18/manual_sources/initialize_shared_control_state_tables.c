/* Recovered behavior:
 * Set the shared controller's active flag and pointer, initialize two byte defaults to 72, clear
 * its fixed fields and 40-, 120-, and 40-entry tables, set the final status byte, and return one.
 */

#include <stdint.h>
__attribute__((used, naked, section(".text.initialize_shared_control_state_tables"))) void
initialize_shared_control_state_tables(void) {
    __asm__ volatile(
        /* The pointed-to controller owns a 0x414-byte state object. */
        "push {r4, r5, lr}\n"
        "ldr r1, [pc, #124]\n"
        "movs r5, #1\n"
        "strb r5, [r1, #0]\n"
        "ldr r0, [pc, #120]\n"
        "str r0, [r1, #4]\n"
        "movs r2, #0\n"
        "strb r2, [r0, #0]\n"
        "movs r1, #72	@ 0x48\n"
        "strb r1, [r0, #1]\n"
        "strb r1, [r0, #2]\n"
        "strh r2, [r0, #4]\n"
        "str r2, [r0, #8]\n"
        "str r2, [r0, #32]\n"
        "str r2, [r0, #36]	@ 0x24\n"
        "str r2, [r0, #20]\n"
        "str r2, [r0, #24]\n"
        "str r2, [r0, #28]\n"
        "str r2, [r0, #40]	@ 0x28\n"
        "str r2, [r0, #44]	@ 0x2c\n"
        "str r2, [r0, #48]	@ 0x30\n"
        "str r2, [r0, #64]	@ 0x40\n"
        "str r2, [r0, #60]	@ 0x3c\n"
        "str r2, [r0, #56]	@ 0x38\n"
        "str r2, [r0, #52]	@ 0x34\n"
        "str r2, [r0, #68]	@ 0x44\n"
        "str r2, [r0, #76]	@ 0x4c\n"
        "movs r1, #80	@ 0x50\n"
        "str r2, [r0, #72]	@ 0x48\n"
        "strb r2, [r1, r0]\n"
        "movs r1, #0\n"
        /* Clear 40 entries at state+0x52/+0xa2 and paired words at +0xf4/+0xf8. */
        ".L_initialize_shared_control_state_tables_block_at_d908_at_07fcd946:\n"
        "lsls r3, r1, #1\n"
        "adds r3, r3, r0\n"
        "movs r4, #82	@ 0x52\n"
        "strh r2, [r4, r3]\n"
        "adds r3, #128	@ 0x80\n"
        "strh r2, [r3, #34]	@ 0x22\n"
        "lsls r3, r1, #3\n"
        "adds r3, r3, r0\n"
        "adds r3, #128	@ 0x80\n"
        "adds r1, r1, #1\n"
        "str r2, [r3, #116]	@ 0x74\n"
        "uxth r1, r1\n"
        "str r2, [r3, #120]	@ 0x78\n"
        "cmp r1, #40	@ 0x28\n"
        "bcc.n .L_initialize_shared_control_state_tables_block_at_d908_at_07fcd946 /* branch: cc, target at .-28 */ /* "
        "0x07fcd962 */\n"
        /* Clear 120 words beginning at state+0x234. */
        "movs r1, #0\n"
        ".L_initialize_shared_control_state_tables_block_at_d908_at_07fcd966:\n"
        "lsls r4, r1, #2\n"
        "adds r3, r4, r0\n"
        "adds r3, #255	@ 0xff\n"
        "adds r3, #255	@ 0xff\n"
        "adds r3, #2\n"
        "adds r1, r1, #1\n"
        "uxth r1, r1\n"
        "str r2, [r3, #52]	@ 0x34\n"
        "cmp r1, #120	@ 0x78\n"
        "bcc.n .L_initialize_shared_control_state_tables_block_at_d908_at_07fcd966 /* branch: cc, target at .-18 */ /* "
        "0x07fcd978 */\n"
        "movs r1, #1\n"
        "lsls r1, r1, #10\n"
        "adds r0, r0, r1\n"
        "strb r5, [r0, #20]\n"
        "movs r0, #1\n"
        "pop {r4, r5, pc}\n");
}
