/* Search the circular record queue, compact it when needed, and submit a record. */
#include <stdint.h>
__attribute__((used, naked, section(".text.search_circular_record_queue_and_compact_if_needed"))) void
search_circular_record_queue_and_compact_if_needed(const void *record) {
    __asm__ volatile("push {r4, r5, r6, r7, lr}\n"
                     "sub sp, #20\n"
                     "str r0, [sp, #12]\n"
                     "ldr r1, [pc, #172]\n"
                     "ldr r0, [r1, #52]\n"
                     "str r0, [sp, #16]\n"
                     "ldr r6, [r1, #56]\n"
                     "mov r7, r1\n"
                     "adds r7, #60\n"
                     "ldmia r7, {r0, r4, r7} /* ldmia r7!, {r0, r4, r7} */\n"
                     "subs r0, r0, #1 /* subs r0, r0, #1 */\n"
                     "str r0, [sp, #8]\n"
                     "movs r5, #0\n"
                     "str r6, [sp, #4]\n"
                     ".Lscan: ldr r0, [sp, #16]\n"
                     "cmp r6, r0\n"
                     "beq .Lflush\n"
                     "mov r0, r6\n"
                     "muls r0, r4\n"
                     "adds r0, r7, r0\n"
                     "movs r2, #20\n"
                     "ldr r1, [sp, #12]\n"
                     "bl memcmp\n"
                     "cmp r0, #0\n"
                     "beq .Lnot_found\n"
                     "adds r6, r6, #1 /* adds r6, r6, #1 */\n"
                     "ldr r0, [sp, #8]\n"
                     "ands r6, r0\n"
                     "adds r5, r5, #1 /* adds r5, r5, #1 */\n"
                     "b .Lscan\n"
                     ".Lnot_found: ldr r1, [sp, #4]\n"
                     "cmp r6, r1\n"
                     "beq .Lreturn\n"
                     "ldr r0, [sp, #16]\n"
                     "subs r0, r0, r1\n"
                     "ldr r1, [sp, #8]\n"
                     "ands r0, r1\n"
                     "cmp r0, r5\n"
                     "bls .Lflush\n"
                     "ldr r0, [sp, #4]\n"
                     "adds r4, r0, r5\n"
                     "ldr r1, [sp, #8]\n"
                     "ands r4, r1\n"
                     "ldr r0, [sp, #16]\n"
                     "subs r5, r0, #1 /* subs r5, r0, #1 */\n"
                     "ands r5, r1\n"
                     "ldr r7, [pc, #84]\n"
                     ".Lcompact: cmp r4, r5\n"
                     "beq .Lcompact_done\n"
                     "mov r3, r7\n"
                     "adds r3, #60\n"
                     "ldmia r3, {r1, r2, r3} /* ldmia r3!, {r1, r2, r3} */\n"
                     "adds r6, r4, #1 /* adds r6, r4, #1 */\n"
                     "muls r4, r2\n"
                     "adds r0, r3, r4\n"
                     "subs r4, r1, #1 /* subs r4, r1, #1 */\n"
                     "ands r4, r6\n"
                     "mov r1, r2\n"
                     "muls r1, r4\n"
                     "adds r1, r3, r1\n"
                     "bl __aeabi_memcpy\n"
                     "b .Lcompact\n"
                     ".Lcompact_done: str r5, [r7, #52]\n"
                     ".Lflush: ldr r0, [sp, #12]\n"
                     "bl advance_ring_s_queue_and_submit_entry\n"
                     ".Lreturn: add sp, #20\n"
                     "pop {r4, r5, r6, r7, pc}\n");
}
