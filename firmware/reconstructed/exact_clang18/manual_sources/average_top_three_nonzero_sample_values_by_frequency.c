/* Recovered behavior:
 * Destructively count nonzero samples, select up to three distinct values with the highest
 * frequencies (reuse the top value if needed), and return their integer average.
 */
#include <stdint.h>
#include "firmware/reconstructed/include/sr08_arm_eabi.h"

/*
 * Count occurrences of nonzero sample values, select up to three distinct
 * values with the highest occurrence counts, and return their integer
 * average. Equal-frequency choices keep the first qualifying value in array
 * order; if fewer than three distinct nonzero values exist, the first choice
 * is reused to fill the missing positions.
 *
 * The counting pass is destructive: after counting a nonzero value, it
 * replaces each later duplicate in `samples` with zero. The byte-count table
 * is local scratch space. The final arithmetic uses signed integer division
 * by three, so the result is truncated toward zero.
 *
 * The pinned body records the exact loop and scratch-space layout used by
 * V204; keeping its behavior and side effect explicit makes the assembly
 * reviewable without implying that the input is preserved.
 */
__attribute__((used, naked, section(".text.average_top_three_nonzero_sample_values_by_frequency"))) uint32_t
average_top_three_nonzero_sample_values_by_frequency(uint32_t *samples, int32_t count) {
    __asm__ volatile("push {r4, r5, r6, r7, lr}\n"
                     "sub sp, #52\n"
                     "mov r4, r1\n"
                     "mov r5, r0\n"
                     "movs r1, #28\n"
                     "mov r0, sp\n"
                     "bl __aeabi_memclr\n"
                     "mov r1, sp\n"
                     "movs r0, #0\n"
                     "ldrsb r0, [r1, r0]\n"
                     "mov lr, r0\n"
                     "movs r0, #0\n"
                     "str r0, [sp, #36]\n"
                     "mov r2, r0\n"
                     "mov r3, r0\n"
                     "mov ip, r0\n"
                     "str r0, [sp, #44]\n"
                     "b .Lclear_counts_test\n"
                     ".Lclear_count_entry: movs r1, #0\n"
                     "mov r6, sp\n"
                     "strb r1, [r6, r0]\n"
                     "adds r0, r0, #1\n"
                     "sxtb r0, r0\n"
                     ".Lclear_counts_test: cmp r0, r4\n"
                     "blt .Lclear_count_entry\n"
                     "movs r1, #0\n"
                     "subs r0, r4, #1\n"
                     "str r0, [sp, #32]\n"
                     "b .Lcount_outer_test\n"
                     ".Lcount_outer_item: adds r0, r1, #1\n"
                     "sxtb r0, r0\n"
                     "lsls r6, r1, #2\n"
                     "str r6, [sp, #40]\n"
                     "str r0, [sp, #28]\n"
                     "b .Lcount_inner_test\n"
                     ".Lcount_duplicate_item: ldr r6, [sp, #40]\n"
                     "lsls r7, r0, #2\n"
                     "ldr r6, [r5, r6]\n"
                     "str r7, [sp, #48]\n"
                     "ldr r7, [r5, r7]\n"
                     "cmp r6, r7\n"
                     "bne .Lcount_inner_next\n"
                     "cmp r6, #0\n"
                     "beq .Lcount_inner_next\n"
                     "cmp r7, #0\n"
                     "beq .Lcount_inner_next\n"
                     "mov r6, sp\n"
                     "ldrb r7, [r6, r1]\n"
                     "adds r7, r7, #1\n"
                     "strb r7, [r6, r1]\n"
                     "ldr r7, [sp, #48]\n"
                     "movs r6, #0\n"
                     "str r6, [r5, r7]\n"
                     ".Lcount_inner_next: adds r0, r0, #1\n"
                     "sxtb r0, r0\n"
                     ".Lcount_inner_test: cmp r0, r4\n"
                     "blt .Lcount_duplicate_item\n"
                     "ldr r0, [sp, #40]\n"
                     "ldr r0, [r5, r0]\n"
                     "cmp r0, #0\n"
                     "beq .Lcount_outer_next\n"
                     "mov r0, sp\n"
                     "ldrb r6, [r0, r1]\n"
                     "adds r6, r6, #1\n"
                     "strb r6, [r0, r1]\n"
                     ".Lcount_outer_next: ldr r1, [sp, #28]\n"
                     "ldr r0, [sp, #32]\n"
                     ".Lcount_outer_test:"
                     "cmp r1, r0\n"
                     "blt .Lcount_outer_item\n"
                     "lsls r0, r4, #2\n"
                     "adds r0, r0, r5\n"
                     "subs r0, #128\n"
                     "ldr r0, [r0, #124]\n"
                     "cmp r0, #0\n"
                     "beq .Lcount_last_sample_complete\n"
                     "mov r0, sp\n"
                     "adds r0, r0, r4\n"
                     "subs r0, #32\n"
                     "ldrb r1, [r0, #31]\n"
                     "adds r1, r1, #1\n"
                     "strb r1, [r0, #31]\n"
                     ".Lcount_last_sample_complete: movs r0, #0\n"
                     "mov r7, sp\n"
                     "b .Lfind_max_count_test\n"
                     ".Lconsider_max_count: ldrsb r1, [r7, r0]\n"
                     "cmp r1, lr\n"
                     "ble .Lmax_count_next\n"
                     "mov lr, r1\n"
                     "lsls r1, r0, #2\n"
                     "ldr r2, [r5, r1]\n"
                     ".Lmax_count_next: adds r0, r0, #1\n"
                     "sxtb r0, r0\n"
                     ".Lfind_max_count_test: cmp r0, r4\n"
                     "blt .Lconsider_max_count\n"
                     "movs r0, #0\n"
                     "b .Lfind_second_count_test\n"
                     ".Lconsider_second_count: ldrsb r1, [r7, r0]\n"
                     "ldr r6, [sp, #36]\n"
                     "cmp r1, r6\n"
                     "ble .Lsecond_count_next\n"
                     "cmp r1, lr\n"
                     "bgt .Lsecond_count_next\n"
                     "lsls r6, r0, #2\n"
                     "ldr r6, [r5, r6]\n"
                     "cmp r6, r2\n"
                     "beq .Lsecond_count_next\n"
                     "mov r3, r6\n"
                     "str r1, [sp, #36]\n"
                     ".Lsecond_count_next: adds r0, r0, #1\n"
                     "sxtb r0, r0\n"
                     ".Lfind_second_count_test: cmp r0, r4\n"
                     "blt .Lconsider_second_count\n"
                     "movs r0, #0\n"
                     "b .Lfind_third_count_test\n"
                     ".Lconsider_third_count: ldrsb r1, [r7, r0]\n"
                     "ldr r6, [sp, #44]\n"
                     "cmp r1, r6\n"
                     "ble .Lthird_count_next\n"
                     "ldr r6, [sp, #36]\n"
                     "cmp r1, r6\n"
                     "bgt .Lthird_count_next\n"
                     "lsls r6, r0, #2\n"
                     "ldr r6, [r5, r6]\n"
                     "cmp r6, r3\n"
                     "beq .Lthird_count_next\n"
                     "cmp r6, r2\n"
                     "beq .Lthird_count_next\n"
                     "mov ip, r6\n"
                     "str r1, [sp, #44]\n"
                     ".Lthird_count_next: adds r0, r0, #1\n"
                     "sxtb r0, r0\n"
                     ".Lfind_third_count_test: cmp r0, r4\n"
                     "blt .Lconsider_third_count\n"
                     "cmp r3, #0\n"
                     "bne .Lensure_second_value\n"
                     "mov r3, r2\n"
                     ".Lensure_second_value: mov r0, ip\n"
                     "cmp r0, #0\n"
                     "bne .Laverage_selected_values\n"
                     "mov ip, r2\n"
                     ".Laverage_selected_values: adds r1, r2, r3\n"
                     "mov r0, ip\n"
                     "adds r0, r1, r0\n"
                     "movs r1, #3\n"
                     "bl __aeabi_idiv\n"
                     "add sp, #52\n"
                     "pop {r4, r5, r6, r7, pc}\n");
}
